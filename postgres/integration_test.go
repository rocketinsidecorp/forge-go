func TestUUIDv7RoundTripAndOrdering(t *testing.T) {
	t.Parallel()
	db := postgrestest.New(t)
	postgrestest.RequireUUIDv7(t, db)
	ctx := context.Background()
	if _, err := db.Exec(ctx, "CREATE TABLE items (id uuid PRIMARY KEY DEFAULT uuidv7(), seq int NOT NULL)"); err != nil {
		t.Fatal(err)
	}
	var generated []uuid.UUID
	for seq := range 50 {
		id := uuid.MustNew()
		generated = append(generated, id)
		if _, err := db.Exec(ctx, "INSERT INTO items (id, seq) VALUES ($1, $2)", id, seq); err != nil {
			t.Fatal(err)
		}
	}
	rows, err := db.Query(ctx, "SELECT id FROM items ORDER BY id")
	if err != nil {
		t.Fatal(err)
	}
	stored, err := pgx.CollectRows(rows, pgx.RowTo[uuid.UUID])
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(stored, generated) {
		t.Fatal("PostgreSQL uuid ordering differs from UUIDv7 generation order")
	}

	// IDs generated by the database default scan into uuid.UUID too.
	var fromDefault uuid.UUID
	if err := db.QueryRow(ctx, "INSERT INTO items (seq) VALUES (99) RETURNING id").Scan(&fromDefault); err != nil {
		t.Fatal(err)
	}
	if fromDefault.Version() != 7 || fromDefault.Compare(generated[len(generated)-1]) <= 0 {
		t.Fatalf("database default id %s is not a later UUIDv7", fromDefault)
	}
}

