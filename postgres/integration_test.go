func TestInTxCommitRollbackAndPanic(t *testing.T) {
	t.Parallel()
	db := postgrestest.New(t)
	ctx := context.Background()
	if _, err := db.Exec(ctx, "CREATE TABLE counters (name text PRIMARY KEY)"); err != nil {
		t.Fatal(err)
	}
	insert := func(name string) func(pgx.Tx) error {
		return func(tx pgx.Tx) error {
			_, err := tx.Exec(ctx, "INSERT INTO counters (name) VALUES ($1)", name)
			return err
		}
	}
	if err := db.InTx(ctx, insert("committed")); err != nil {
		t.Fatal(err)
	}
	sentinel := errors.New("business rule failed")
	if err := db.InTx(ctx, func(tx pgx.Tx) error { _ = insert("rolled-back")(tx); return sentinel }); !errors.Is(err, sentinel) {
		t.Fatalf("fn error must be returned unchanged, got %v", err)
	}
	func() {
		defer func() { _ = recover() }()
		_ = db.InTx(ctx, func(tx pgx.Tx) error { _ = insert("panicked")(tx); panic("boom") })
	}()

	rows, err := db.Query(ctx, "SELECT name FROM counters ORDER BY name")
	if err != nil {
		t.Fatal(err)
	}
	names, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(names, []string{"committed"}) {
		t.Fatalf("rows=%v, want only the committed one", names)
	}
	if stat := db.Pool().Stat(); stat.AcquiredConns() != 0 {
		t.Fatalf("%d connections leaked", stat.AcquiredConns())
	}
}

func TestInTenantTxEnforcesRLSAndDoesNotLeakTenant(t *testing.T) {
	db := postgrestest.New(t)
	ctx := context.Background()
	role := "forge_rls_" + strings.ReplaceAll(uuid.MustNew().String(), "-", "")[:16]
	quotedRole := pgx.Identifier{role}.Sanitize()
	if _, err := db.Exec(ctx, "CREATE ROLE "+quotedRole+" NOLOGIN"); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, _ = db.Exec(context.Background(), "DROP OWNED BY "+quotedRole)
		_, _ = db.Exec(context.Background(), "DROP ROLE "+quotedRole)
	})
	if _, err := db.Exec(ctx, `
		CREATE TABLE tenant_documents (id uuid PRIMARY KEY, tenant_id uuid NOT NULL, title text NOT NULL);
		ALTER TABLE tenant_documents ENABLE ROW LEVEL SECURITY;
		ALTER TABLE tenant_documents FORCE ROW LEVEL SECURITY;
		CREATE POLICY tenant_documents_isolation ON tenant_documents
			USING (tenant_id::text = current_setting('forge.tenant_id', true))
			WITH CHECK (tenant_id::text = current_setting('forge.tenant_id', true));
		GRANT SELECT, INSERT ON tenant_documents TO `+quotedRole); err != nil {
		t.Fatal(err)
	}
	tenantA, _ := tenancy.New(uuid.MustNew())
	tenantB, _ := tenancy.New(uuid.MustNew())
	if _, err := db.Exec(ctx, "INSERT INTO tenant_documents (id, tenant_id, title) VALUES ($1, $2, 'a'), ($3, $4, 'b')",
		uuid.MustNew(), tenantA.ID, uuid.MustNew(), tenantB.ID); err != nil {
		t.Fatal(err)
	}

	tenantContext := func(tenant tenancy.Tenant) context.Context {
		result, err := tenancy.WithContext(ctx, tenant)
		if err != nil {
			t.Fatal(err)
		}
		return result
	}
	assertVisible := func(tenant tenancy.Tenant, want string) {
		t.Helper()
		err := db.InTenantTx(tenantContext(tenant), func(tx pgx.Tx) error {
			if _, err := tx.Exec(ctx, "SET LOCAL ROLE "+quotedRole); err != nil {
				return err
			}
			rows, err := tx.Query(ctx, "SELECT title FROM tenant_documents ORDER BY title")
			if err != nil {
				return err
			}
			titles, err := pgx.CollectRows(rows, pgx.RowTo[string])
			if err != nil {
				return err
			}
			if !slices.Equal(titles, []string{want}) {
				return fmt.Errorf("tenant saw titles %v, want [%s]", titles, want)
			}
			if _, err := tx.Exec(ctx, "SAVEPOINT cross_tenant_insert"); err != nil {
				return fmt.Errorf("savepoint cross-tenant insert: %w", err)
			}
			other := tenantA
			if tenant == tenantA {
				other = tenantB
			}
			_, err = tx.Exec(ctx, "INSERT INTO tenant_documents (id, tenant_id, title) VALUES ($1, $2, 'cross-tenant')", uuid.MustNew(), other.ID)
			if err == nil {
				return errors.New("RLS allowed a cross-tenant insert")
			}
			var pgErr *pgconn.PgError
			if !errors.As(err, &pgErr) || pgErr.Code != "42501" {
				return fmt.Errorf("cross-tenant insert failed for an unexpected reason: %w", err)
			}
			if _, err := tx.Exec(ctx, "ROLLBACK TO SAVEPOINT cross_tenant_insert"); err != nil {
				return fmt.Errorf("rollback cross-tenant insert: %w", err)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	assertVisible(tenantA, "a")
	assertVisible(tenantB, "b")

	if err := db.InTenantTx(context.Background(), func(pgx.Tx) error { return nil }); !errors.Is(err, tenancy.ErrMissing) {
		t.Fatalf("missing tenant error=%v", err)
	}
	var leaked string
	if err := db.QueryRow(ctx, "SELECT current_setting('forge.tenant_id', true)").Scan(&leaked); err != nil {
		t.Fatal(err)
	}
	if leaked != "" {
		t.Fatalf("tenant setting leaked into pooled session: %q", leaked)
	}
}

// TestSerializableRetry forces a serialization failure: both transactions
// read the same rows before either writes, so one must abort with 40001.
func TestSerializableRetry(t *testing.T) {
	t.Parallel()
	db := postgrestest.New(t)
	ctx := context.Background()
	if _, err := db.Exec(ctx, "CREATE TABLE doctors (name text PRIMARY KEY, on_call bool NOT NULL); INSERT INTO doctors VALUES ('a', true), ('b', true)"); err != nil {
		t.Fatal(err)
	}
	var barrier sync.WaitGroup
	barrier.Add(2)
	var attempts sync.Map
	goOffCall := func(name string, opts postgres.TxOptions) error {
		return db.InTxWith(ctx, opts, func(tx pgx.Tx) error {
			count, _ := attempts.LoadOrStore(name, new(int))
			*count.(*int)++
			var onCall int
			if err := tx.QueryRow(ctx, "SELECT count(*) FROM doctors WHERE on_call").Scan(&onCall); err != nil {
				return err
			}
			if *count.(*int) == 1 {
				barrier.Done()
				barrier.Wait() // both have read before either writes
			}
			if onCall < 2 {
				return nil // someone must stay on call
			}
			_, err := tx.Exec(ctx, "UPDATE doctors SET on_call = false WHERE name = $1", name)
			return err
		})
	}
	opts := postgres.TxOptions{Isolation: postgres.Serializable, Attempts: 5}
	errs := make(chan error, 2)
	for _, name := range []string{"a", "b"} {
		go func() { errs <- goOffCall(name, opts) }()
	}
	for range 2 {
		if err := <-errs; err != nil {
			t.Fatalf("retry did not resolve the serialization failure: %v", err)
		}
	}
	var onCall int
	if err := db.QueryRow(ctx, "SELECT count(*) FROM doctors WHERE on_call").Scan(&onCall); err != nil {
		t.Fatal(err)
	}
	if onCall != 1 {
		t.Fatalf("on_call=%d: serializable invariant violated", onCall)
	}
	retried := 0
	attempts.Range(func(_, count any) bool { retried += *count.(*int) - 1; return true })
	if retried == 0 {
		t.Fatal("expected at least one retry")
	}
}

func TestTranslateAgainstRealConstraints(t *testing.T) {
	t.Parallel()
	db := postgrestest.New(t)
	ctx := context.Background()
	if _, err := db.Exec(ctx, `
		CREATE TABLE projects (id uuid PRIMARY KEY);
		CREATE TABLE tasks (
			id uuid PRIMARY KEY,
			project_id uuid REFERENCES projects (id),
			title text NOT NULL CONSTRAINT tasks_title_length CHECK (length(title) <= 5),
			CONSTRAINT tasks_title_key UNIQUE (title)
		)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(ctx, "INSERT INTO tasks (id, title) VALUES ($1, 'a')", uuid.MustNew()); err != nil {
		t.Fatal(err)
	}
	cases := []struct {
		name, sql string
		args      []any
		wantCode  string
	}{
		{"unique", "INSERT INTO tasks (id, title) VALUES ($1, 'a')", []any{uuid.MustNew()}, "already_exists"},
		{"foreign key", "INSERT INTO tasks (id, project_id, title) VALUES ($1, $2, 'b')", []any{uuid.MustNew(), uuid.MustNew()}, "reference_violation"},
		{"check", "INSERT INTO tasks (id, title) VALUES ($1, 'too long')", []any{uuid.MustNew()}, "constraint_violation"},
		{"not null", "INSERT INTO tasks (id, title) VALUES ($1, NULL)", []any{uuid.MustNew()}, "internal_error"},
	}
	for _, test := range cases {
		_, err := db.Exec(ctx, test.sql, test.args...)
		if translated := fault.From(postgres.Translate(err)); translated == nil || translated.Code != test.wantCode {
			t.Errorf("%s: got %v", test.name, err)
		}
	}
	var missing uuid.UUID
	err := db.QueryRow(ctx, "SELECT id FROM tasks WHERE title = 'none'").Scan(&missing)
	if translated := fault.From(postgres.Translate(err)); translated == nil || translated.Status() != http.StatusNotFound {
		t.Errorf("no rows: got %v", err)
	}
}

func TestAdvisoryXactLock(t *testing.T) {
	t.Parallel()
	db := postgrestest.New(t)
	ctx := context.Background()
	key := postgres.LockKey("test:advisory")
	held := make(chan struct{})
	release := make(chan struct{})
	done := make(chan error, 1)
	go func() {
		done <- db.InTx(ctx, func(tx pgx.Tx) error {
			if err := postgres.AdvisoryXactLock(ctx, tx, key); err != nil {
				return err
			}
			close(held)
			<-release
			return nil
		})
	}()
	<-held
	err := db.InTx(ctx, func(tx pgx.Tx) error {
		acquired, err := postgres.TryAdvisoryXactLock(ctx, tx, key)
		if err == nil && acquired {
			return errors.New("lock acquired while another transaction holds it")
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	close(release)
	if err := <-done; err != nil {
		t.Fatal(err)
	}
	err = db.InTx(ctx, func(tx pgx.Tx) error {
		acquired, err := postgres.TryAdvisoryXactLock(ctx, tx, key)
		if err == nil && !acquired {
			return errors.New("lock not released at commit")
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
}

