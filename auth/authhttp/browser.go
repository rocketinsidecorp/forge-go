package authhttp

import (
	"errors"
	"net/http"
	"time"

	"github.com/rocketinsidecorp/forge-go/auth"
	"github.com/rocketinsidecorp/forge-go/csrf"
	"github.com/rocketinsidecorp/forge-go/fault"
	"github.com/rocketinsidecorp/forge-go/web"
)

const (
	// ReturnToParameter carries the page a signed-out visitor asked for from
	// AuthenticateBrowser to the sign-in form and back. Validate it with
	// ReturnPath every time it is read.
	ReturnToParameter = "return_to"
	// MFAChallengeCookieName holds the pending second-factor challenge between
	// the password step and the code step of a browser sign-in. It is
	// HttpOnly, Secure, SameSite=Strict and expires with the challenge, so the
	// challenge never appears in a URL, a page or script.
	MFAChallengeCookieName = "__Host-forge_mfa"
)

var (
	// ErrMFAChallengeMissing means the browser has no pending MFA challenge
	// (it expired or the user never passed the password step): start again
	// from the sign-in form.
	ErrMFAChallengeMissing = fault.New("mfa_challenge_missing", "sign in again to continue", fault.CategoryUnauthorized, 0)

	errBrowserMFANotConfigured      = errors.New("auth: browser MFA is not configured")
	errBrowserRecoveryNotConfigured = errors.New("auth: browser password recovery is not configured")
)

// ReturnPath returns candidate when it is a local path that is safe to
// redirect to after signing in (see web.IsLocalPath: no scheme, host,
// scheme-relative "//" or "/\" prefix, backslash, control, space or
// non-ASCII byte, at most 2048 bytes) and fallback otherwise. Use it for
// every value that came from a request, such as ReturnToParameter.
func ReturnPath(candidate, fallback string) string {
	if web.IsLocalPath(candidate) {
		return candidate
	}
	return fallback
}

// SignInStep is where a successful password step leaves a browser sign-in.
type SignInStep int

const (
	// SignInComplete means the session and CSRF cookies are set.
	SignInComplete SignInStep = iota + 1
	// SignInNeedsMFA means the password was right and the account has a
	// second factor: the challenge cookie is set and CompleteMFA finishes the
	// sign-in. No session exists yet.
	SignInNeedsMFA
)

// SignInCredentials is a submitted sign-in form. Tenant is the tenant slug:
// Forge logins always name their tenant explicitly (docs/AUTHENTICATION.md).
type SignInCredentials struct {
	Email    string
	Password string
	Tenant   string
}

// BrowserOptions configures NewBrowser.
type BrowserOptions struct {
	// Login verifies passwords and creates sessions (required).
	Login *auth.LoginService
	// Sessions revokes the session on sign-out (required).
	Sessions auth.SessionRevoker
	// MFA completes sign-ins for accounts with a second factor. Without it,
	// such accounts cannot sign in (LoginService fails closed).
	MFA *auth.MFAService
	// Passwords re-checks the password of a signed-in account before it
	// changes its second factor (step-up). With MFA, it enables the
	// two-factor settings (MFASettingsAvailable).
	Passwords auth.SubjectPasswordStore
	// Recovery enables the password-reset forms.
	Recovery *auth.RecoveryService
	// Auditor records sign-outs. Login, MFA and recovery audit through their
	// own services' auditors.
	Auditor auth.SecurityAuditor
}

// Browser is the security-critical half of server-rendered sign-in, sign-out,
// second-factor and password-reset forms. The application's HTML adapter
// (generated by `forge generate authentication`) decodes the forms, renders
// the pages and chooses the messages; Browser verifies the CSRF token, calls
// the authentication services with the request's network source, and sets or
// clears the browser credentials exactly as the JSON cookie endpoints do.
//
// Every method that changes credentials requires csrf.Verified: the route
// must sit behind csrf.Protection and must not be exempted, otherwise the
// method fails closed with ErrCSRFInvalid. Every method marks the response
// Cache-Control: no-store, and throttled calls set Retry-After, as do calls
// refused because password hashing is saturated (ErrPasswordHashingUnavailable,
// a 503 through web.Error). After a
// method that sets cookies succeeds, redirect: the CSRF token was rotated, so
// a page rendered in the same response would embed the old one.
type Browser struct {
	login    *auth.LoginService
	sessions auth.SessionRevoker
	mfa      *auth.MFAService
	recovery *auth.RecoveryService
	auditor  auth.SecurityAuditor
	// stepUpGate re-authenticates before a two-factor change; nil without
	// MFA or Passwords.
	stepUpGate *auth.MFAStepUpGate
}

// NewBrowser validates options.
func NewBrowser(opts BrowserOptions) (*Browser, error) {
	if opts.Login == nil {
		return nil, errors.New("auth: browser sign-in needs a login service")
	}
	if opts.Sessions == nil {
		return nil, errors.New("auth: browser sign-out needs a session revoker")
	}
	browser := &Browser{
		login:    opts.Login,
		sessions: opts.Sessions,
		mfa:      opts.MFA,
		recovery: opts.Recovery,
		auditor:  opts.Auditor,
	}
	if opts.MFA != nil && opts.Passwords != nil {
		gate, err := auth.NewMFAStepUpGate(opts.Login, opts.MFA, opts.Passwords)
		if err != nil {
			return nil, err
		}
		browser.stepUpGate = gate
	}
	return browser, nil
}

// MFAEnabled reports whether accounts with a second factor can sign in.
func (b *Browser) MFAEnabled() bool { return b.mfa != nil }

// RecoveryEnabled reports whether the password-reset forms work.
func (b *Browser) RecoveryEnabled() bool { return b.recovery != nil }

// SignIn verifies a submitted sign-in form. A wrong email, password or
// tenant, and an inactive account, membership, tenant or organization, are
// all ErrCredentialsInvalid, so the form must show one message that does not
// say which field was wrong. A throttled attempt is *LoginThrottledError
// with Retry-After set. On SignInComplete the session and a fresh CSRF token
// are set in the same cookies NewCookieLoginHandler sets; on SignInNeedsMFA
// only the MFA challenge cookie is set.
func (b *Browser) SignIn(w http.ResponseWriter, r *http.Request, credentials SignInCredentials) (SignInStep, error) {
	noStore(w)
	if !csrf.Verified(r) {
		return 0, ErrCSRFInvalid
	}
	result, err := b.login.Login(r.Context(), auth.LoginInput{
		Email:      credentials.Email,
		Password:   credentials.Password,
		TenantSlug: credentials.Tenant,
		Source:     requestSource(r),
	})
	if err != nil {
		_, _ = logSecurityAuditFailure(r, err)
		var throttled *auth.LoginThrottledError
		switch {
		case errors.As(err, &throttled):
			w.Header().Set("Retry-After", retryAfterHeader(throttled.RetryAfter))
			return 0, throttled
		case errors.Is(err, auth.ErrCredentialsInvalid):
			return 0, auth.ErrCredentialsInvalid
		default:
			setPasswordWorkRetryAfter(w, err)
			return 0, err
		}
	}
	if result.MFARequired {
		setMFAChallengeCookie(w, result.MFAChallenge.Reveal(), result.ExpiresAt)
		return SignInNeedsMFA, nil
	}
	if len(r.CookiesNamed(MFAChallengeCookieName)) > 0 {
		clearMFAChallengeCookie(w)
	}
	if _, err := startCookieSession(w, result); err != nil {
		return 0, err
	}
	return SignInComplete, nil
}

// MFAPending reports whether the browser holds a well-formed MFA challenge
// cookie, so the code form is worth showing. The server still decides
// whether the challenge is valid.
func (b *Browser) MFAPending(r *http.Request) bool {
	_, ok := mfaChallengeCookie(r)
	return b.mfa != nil && ok
}

// CompleteMFA exchanges the pending challenge and a TOTP or backup code for
// a session, setting the same cookies as SignIn. A wrong code, or a
// challenge the server no longer accepts, is ErrMFAInvalid (show the form
// again); no challenge cookie is ErrMFAChallengeMissing (start again from the
// sign-in form); throttling is *LoginThrottledError with Retry-After set.
func (b *Browser) CompleteMFA(w http.ResponseWriter, r *http.Request, code string) error {
	noStore(w)
	if !csrf.Verified(r) {
		return ErrCSRFInvalid
	}
	if b.mfa == nil {
		return errBrowserMFANotConfigured
	}
	challenge, ok := mfaChallengeCookie(r)
	if !ok {
		if len(r.CookiesNamed(MFAChallengeCookieName)) > 0 {
			clearMFAChallengeCookie(w)
		}
		return ErrMFAChallengeMissing
	}
	result, err := b.mfa.CompleteLogin(r.Context(), auth.MFACompletion{
		ChallengeToken: challenge,
		Code:           code,
		Source:         requestSource(r),
	})
	if err != nil {
		_, _ = logSecurityAuditFailure(r, err)
		var throttled *auth.LoginThrottledError
		switch {
		case errors.As(err, &throttled):
			w.Header().Set("Retry-After", retryAfterHeader(throttled.RetryAfter))
			return throttled
		case errors.Is(err, auth.ErrMFAInvalid):
			return auth.ErrMFAInvalid
		default:
			return err
		}
	}
	clearMFAChallengeCookie(w)
	_, err = startCookieSession(w, result)
	return err
}

// SignOut revokes the browser's session, records it with the configured
// auditor, and clears the session, CSRF and MFA challenge cookies. Like
// NewCookieLogoutHandler it is idempotent for missing, unknown or revoked
// sessions; only a failed revocation is an error.
func (b *Browser) SignOut(w http.ResponseWriter, r *http.Request) error {
	noStore(w)
	if !csrf.Verified(r) {
		return ErrCSRFInvalid
	}
	if err := endCookieSession(w, r, b.sessions, b.auditor); err != nil {
		return err
	}
	if len(r.CookiesNamed(MFAChallengeCookieName)) > 0 {
		clearMFAChallengeCookie(w)
	}
	return nil
}

// RequestPasswordReset asks for a reset link. Known, unknown and malformed
// identities all return nil, and so do delivery and audit failures (the
// sender and the request log record those), so the page must show the same
// message whatever happened. Only throttling (*RecoveryThrottledError, with
// Retry-After set, keyed on the submitted identity whether or not it exists)
// and infrastructure failures are errors. The call takes at least the
// RecoveryService's response time (100 ms by default), and with a
// RecoveryDispatcher configured (auth.WithRecoveryDispatcher) the account is
// looked up, and the link issued and delivered, after it returned.
func (b *Browser) RequestPasswordReset(w http.ResponseWriter, r *http.Request, email, tenant string) error {
	noStore(w)
	if !csrf.Verified(r) {
		return ErrCSRFInvalid
	}
	if b.recovery == nil {
		return errBrowserRecoveryNotConfigured
	}
	err := b.recovery.Request(r.Context(), auth.RecoveryRequest{Email: email, TenantSlug: tenant, Source: requestSource(r)})
	if err == nil {
		return nil
	}
	auditFailure, _ := logSecurityAuditFailure(r, err)
	var throttled *auth.RecoveryThrottledError
	var delivery *auth.RecoveryDeliveryError
	switch {
	case errors.As(err, &throttled):
		w.Header().Set("Retry-After", retryAfterHeader(throttled.RetryAfter))
		return throttled
	case errors.As(err, &delivery), auditFailure:
		// Account-dependent failures keep the uniform answer.
		return nil
	default:
		return err
	}
}

// ResetPassword sets a new password with a reset token. A malformed,
// unknown, expired or used token is ErrRecoveryInvalid; an empty or
// oversized password is ErrPasswordInvalid; throttling is
// *RecoveryThrottledError with Retry-After set. On success every session of
// the account is revoked by the store, and this browser's session and CSRF
// cookies are cleared, so the user signs in again with the new password.
func (b *Browser) ResetPassword(w http.ResponseWriter, r *http.Request, token, newPassword string) error {
	noStore(w)
	if !csrf.Verified(r) {
		return ErrCSRFInvalid
	}
	if b.recovery == nil {
		return errBrowserRecoveryNotConfigured
	}
	err := b.recovery.Reset(r.Context(), auth.PasswordReset{Token: token, NewPassword: newPassword, Source: requestSource(r)})
	if err != nil {
		if _, applied := logSecurityAuditFailure(r, err); !applied {
			var throttled *auth.RecoveryThrottledError
			switch {
			case errors.As(err, &throttled):
				w.Header().Set("Retry-After", retryAfterHeader(throttled.RetryAfter))
				return throttled
			case errors.Is(err, auth.ErrRecoveryInvalid):
				return auth.ErrRecoveryInvalid
			case errors.Is(err, auth.ErrPasswordInvalid):
				return auth.ErrPasswordInvalid
			default:
				setPasswordWorkRetryAfter(w, err)
				return err
			}
		}
	}
	clearSessionCookies(w)
	return nil
}

// mfaChallengeCookie returns the single well-formed challenge cookie.
func mfaChallengeCookie(r *http.Request) (string, bool) {
	cookies := r.CookiesNamed(MFAChallengeCookieName)
	if len(cookies) != 1 {
		return "", false
	}
	if _, err := auth.ParseMFAChallengeToken(cookies[0].Value); err != nil {
		return "", false
	}
	return cookies[0].Value, true
}

func setMFAChallengeCookie(w http.ResponseWriter, challenge string, expiresAt time.Time) {
	http.SetCookie(w, &http.Cookie{
		Name:     MFAChallengeCookieName,
		Value:    challenge,
		Path:     "/",
		Expires:  expiresAt.UTC(),
		Secure:   true,
		HttpOnly: true,
		SameSite: http.SameSiteStrictMode,
	})
}

func clearMFAChallengeCookie(w http.ResponseWriter) {
	http.SetCookie(w, &http.Cookie{
		Name:     MFAChallengeCookieName,
		Path:     "/",
		Expires:  time.Unix(1, 0).UTC(),
		MaxAge:   -1,
		Secure:   true,
		HttpOnly: true,
		SameSite: http.SameSiteStrictMode,
	})
}
